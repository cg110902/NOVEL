def write_proposal(ch):
    num = ch["num"]
    tok = f"ch_{num:03d}"
    op_id = f"{tok}.reader.manual.{num:03d}"
    proposal = {
        "schema": "novel-studio.state-mutation/v2",
        "chapter": tok,
        "operation_id": op_id,
        "current": {
            "time": f"2026年9月{10+num}日",
            "location": "余烬书屋" if num % 2 == 0 else "档案馆",
            "situation": ch["goal"],
            "goal": "进入深渊找备份",
            "present_characters": ["陈默", "苏见微", "老秦"],
            "active_pressures": ["非法编辑案", "档案馆鬼域", "芯片读取"],
            "aftershock": ch["goal"][:40]
        },
        "entities": [],
        "lines": ch["lines"],
        "ledger": {"transactions": []},
        "timeline": {"events": ch["events"], "arcs": []},
        "synopsis": {"title": ch["title"], "text": ch["goal"]}
    }
    # 处理 lines: plant 需要额外字段
    for line in proposal["lines"]:
        if line["action"] == "plant":
            # 确保必要字段存在
            if "name" not in line:
                line["name"] = line["id"]
            if "plant_ch" not in line:
                line["plant_ch"] = num
            if "target_ch" not in line:
                line["target_ch"] = 15
            if "weight" not in line:
                line["weight"] = 2
            if "plan" not in line:
                line["plan"] = ch["goal"]
        # knowledge 需要 secret
        if line.get("kind") == "knowledge" and line["action"] == "plant":
            if "secret" not in line:
                line["secret"] = line.get("name", "秘密")
            if "plant_ch" not in line:
                line["plant_ch"] = num
    path = inbox / f"{tok}.json"
    path.write_text(json.dumps(proposal, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"proposal {tok} written")

